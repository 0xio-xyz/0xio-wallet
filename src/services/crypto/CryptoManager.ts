export class CryptoManager {
  isMnemonicWord(word: string): boolean {
    const w = word.trim().toLowerCase();
    return BIP39_WORDS.has(w) || BIP39_LEGACY_WORDS.has(w);
  }

  mnemonicWordlist(): readonly string[] {
    return BIP39_WORDLIST;
  }

  privateKey: string | null;
  publicKey: string | null;
  signingKey: nacl.SignKeyPair | null;

  constructor(privateKey: string | null = null) {
    this.privateKey = privateKey;
    this.publicKey = null;
    this.signingKey = null;
  }

  setPrivateKey(privateKeyBase64: string) {
    try {
      if (!privateKeyBase64 || typeof privateKeyBase64 !== 'string') return false;
      if (!/^[A-Za-z0-9+/]*={0,2}$/.test(privateKeyBase64)) return false;

      const privateKeyBytes = this.base64ToBytes(privateKeyBase64);
      if (privateKeyBytes.length !== 32) return false;

      this.signingKey = nacl.sign.keyPair.fromSeed(privateKeyBytes);
      this.privateKey = privateKeyBase64;
      this.publicKey = this.bytesToBase64(this.signingKey.publicKey);

      return true;
    } catch (_error) {
      return false;
    }
  }

  getPublicKey() {
    return this.publicKey;
  }

  async generateKeyPair() {
    const MAX_ATTEMPTS = 100;
    let attempts = 0;

    while (attempts < MAX_ATTEMPTS) {
      attempts++;

      try {
        const entropy = crypto.getRandomValues(new Uint8Array(16));
        const entropyHex = this.bytesToHex(entropy);

        const mnemonic = await this.entropyToMnemonic(entropyHex);
        const mnemonicWords = mnemonic.split(' ');

        const seed = await this.mnemonicToSeed(mnemonic);
        const seedHex = this.bytesToHex(seed);

        // Canonical derivation: use master root key directly
        const masterKey = await this.deriveMasterKey(seed);
        const masterChainHex = this.bytesToHex(masterKey.chainCode);

        const signingKey = nacl.sign.keyPair.fromSeed(masterKey.privateKey);

        const privateKeyRaw = masterKey.privateKey;
        const publicKeyRaw = signingKey.publicKey;

        const privateKeyB64 = this.bytesToBase64(privateKeyRaw);
        const publicKeyB64 = this.bytesToBase64(publicKeyRaw);

        const address = await this.deriveAddress(publicKeyB64);

        // Address must be exactly 47 chars ('oct' + 44 base58); if short, regenerate (grinding)
        if (!this.verifyAddressFormat(address)) {
          logger.debug(`Address length ${address?.length}, regenerating... (attempt ${attempts})`);
          continue;
        }

        this.signingKey = signingKey;
        this.privateKey = privateKeyB64;
        this.publicKey = publicKeyB64;

        return {
          mnemonic: mnemonicWords,
          seed_hex: seedHex,
          master_chain_hex: masterChainHex,
          private_key_hex: this.bytesToHex(privateKeyRaw),
          public_key_hex: this.bytesToHex(publicKeyRaw),
          private_key_b64: privateKeyB64,
          public_key_b64: publicKeyB64,
          address: address,
        };
      } catch (error) {
        logger.error('Generation attempt error:', error);
      }
    }

    logger.error(`Failed to generate valid address after ${MAX_ATTEMPTS} attempts`);
    return null;
  }

  async recoverFromMnemonic(mnemonicPhrase: string) {
    try {
      const words = mnemonicPhrase.trim().split(/\s+/);
      if (words.length < 12) {
        throw new Error('Invalid mnemonic phrase - must be at least 12 words');
      }

      const seed = await this.mnemonicToSeed(mnemonicPhrase.trim());
      const masterKey = await this.deriveMasterKey(seed);

      const processKey = async (keyBytes: Uint8Array, label: string) => {
        const kp = nacl.sign.keyPair.fromSeed(keyBytes);
        const pkB64 = this.bytesToBase64(kp.publicKey);
        const rawAddress = await this.deriveAddress(pkB64);

        let isPadded = false;
        let paddedAddress = rawAddress;

        // Detect legacy padding bug: base58 part < 44 chars was left-padded with '1'
        const base58Part = rawAddress.substring(3);
        if (base58Part.length < 44) {
          let tempHash = base58Part;
          while (tempHash.length < 44) {
            tempHash = '1' + tempHash;
          }
          paddedAddress = 'oct' + tempHash;
          isPadded = true;
        }

        return {
          label: label,
          address: paddedAddress,
          canonicalAddress: rawAddress,
          privateKey: this.bytesToBase64(keyBytes),
          publicKey: pkB64,
          mnemonic: words,
          isPadded: isPadded,
          addressWarning: isPadded
            ? 'CRITICAL: This wallet was generated with a padding bug. Transactions will likely fail.'
            : null,
        };
      };

      const masterCandidate = await processKey(masterKey.privateKey, 'Master (Root)');

      return masterCandidate;
    } catch (error) {
      logger.error('Recovery error:', error);
      throw new Error(`Failed to recover from mnemonic: ${error.message}`);
    }
  }

  async importWallet(privateKeyBase64: string) {
    try {
      if (!privateKeyBase64 || typeof privateKeyBase64 !== 'string') {
        throw new Error('Private key must be a non-empty string');
      }

      const privateKeyBytes = this.base64ToBytes(privateKeyBase64);
      this.signingKey = nacl.sign.keyPair.fromSeed(privateKeyBytes);

      const publicKeyRaw = this.signingKey.publicKey;
      const publicKeyB64 = this.bytesToBase64(publicKeyRaw);

      this.privateKey = privateKeyBase64;
      this.publicKey = publicKeyB64;

      const rawAddress = await this.deriveAddress(publicKeyB64);

      let isPadded = false;
      let paddedAddress = rawAddress;

      // Detect legacy padding bug: base58 part < 44 chars was left-padded with '1'
      const base58Part = rawAddress.substring(3);
      if (base58Part.length < 44) {
        let tempHash = base58Part;
        while (tempHash.length < 44) {
          tempHash = '1' + tempHash;
        }
        paddedAddress = 'oct' + tempHash;
        isPadded = true;
      }

      return {
        private_key_b64: privateKeyBase64,
        public_key_b64: publicKeyB64,
        address: paddedAddress,
        canonicalAddress: rawAddress,
        isPadded: isPadded,
        addressWarning: isPadded
          ? 'CRITICAL: This wallet was generated with a padding bug. Transactions will likely fail.'
          : null,
      };
    } catch (error) {
      throw new Error(`Failed to import wallet: ${error.message}`);
    }
  }

  /** No padding -- short addresses mean caller must regenerate keys. */
  async deriveAddress(publicKey: string) {
    try {
      const publicKeyBytes = this.base64ToBytes(publicKey);

      const hash = await this.sha256(publicKeyBytes);

      const base58Hash = this.bytesToBase58(hash);

      return 'oct' + base58Hash;
    } catch (_error) {
      return null;
    }
  }

  verifyAddressFormat(address: string) {
    if (!address || typeof address !== 'string') return false;
    if (!address.startsWith('oct')) return false;
    if (address.length !== 47) return false;

    const BASE58_ALPHABET = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
    const base58Part = address.slice(3);
    for (const char of base58Part) {
      if (!BASE58_ALPHABET.includes(char)) return false;
    }

    return true;
  }

  async deriveMasterKey(seed: Uint8Array) {
    const key = this.stringToBytes('Octra seed');
    const hmac = await this.hmacSha512(key, seed);

    return {
      privateKey: hmac.slice(0, 32),
      chainCode: hmac.slice(32, 64),
    };
  }

  async deriveAccountAtIndex(mnemonic: string, index: number) {
    if (!Number.isSafeInteger(index) || index < 0 || index > 0xffffffff) {
      throw new Error('Invalid account number');
    }
    const seed = await this.mnemonicToSeed(mnemonic);
    let input: Uint8Array;
    if (index === 0) {
      input = seed;
    } else {
      const idxBytes = new Uint8Array(4);
      new DataView(idxBytes.buffer).setUint32(0, index, true); // little-endian
      input = new Uint8Array([...seed, ...idxBytes]);
    }
    const key = this.stringToBytes('Octra seed');
    const hmac = await this.hmacSha512(key, input);
    const privateKey = hmac.slice(0, 32);
    const signingKey = nacl.sign.keyPair.fromSeed(privateKey);
    const publicKeyB64 = this.bytesToBase64(signingKey.publicKey);
    const address = await this.deriveAddress(publicKeyB64);
    return {
      privateKey: this.bytesToBase64(privateKey),
      publicKey: publicKeyB64,
      address,
      index,
    };
  }

  async sha256(data: Uint8Array) {
    const hashBuffer = await crypto.subtle.digest('SHA-256', data as BufferSource);
    return new Uint8Array(hashBuffer);
  }

  async hmacSha512(key: Uint8Array, data: Uint8Array) {
    const cryptoKey = await crypto.subtle.importKey(
      'raw',
      key as BufferSource,
      { name: 'HMAC', hash: 'SHA-512' },
      false,
      ['sign']
    );
    const signature = await crypto.subtle.sign('HMAC', cryptoKey, data as BufferSource);
    return new Uint8Array(signature);
  }

  async entropyToMnemonic(entropyHex: string) {
    const entropy = this.hexToBytes(entropyHex);
    const entropyBits = Array.from(entropy)
      .map((byte) => byte.toString(2).padStart(8, '0'))
      .join('');
    const hash = await this.sha256(entropy);
    const hashBits = Array.from(hash)
      .map((byte) => byte.toString(2).padStart(8, '0'))
      .join('');
    const checksum = hashBits.slice(0, entropy.length / 4);
    const fullBits = entropyBits + checksum;

    const words = [];
    for (let i = 0; i < fullBits.length; i += 11) {
      const index = parseInt(fullBits.slice(i, i + 11), 2);
      words.push(BIP39_WORDLIST[index]);
    }
    return words.join(' ');
  }

  async mnemonicToSeed(mnemonic: string, passphrase = '') {
    const mnemonicBuffer = this.stringToBytes(mnemonic);
    const saltBuffer = this.stringToBytes('mnemonic' + passphrase);
    const keyMaterial = await crypto.subtle.importKey('raw', mnemonicBuffer, 'PBKDF2', false, [
      'deriveBits',
    ]);
    const derivedBits = await crypto.subtle.deriveBits(
      { name: 'PBKDF2', salt: saltBuffer, iterations: 2048, hash: 'SHA-512' },
      keyMaterial,
      512
    );
    return new Uint8Array(derivedBits);
  }

  stringToBytes(str: string) {
    return new TextEncoder().encode(str);
  }
  bytesToBase64(bytes: Uint8Array | number[]) {
    return btoa(String.fromCharCode(...bytes));
  }
  base64ToBytes(base64: string) {
    const bin = atob(base64);
    const bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    return bytes;
  }
  bytesToHex(bytes: Uint8Array | number[]) {
    return Array.from(bytes)
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('');
  }
  hexToBytes(hex: string) {
    const bytes = new Uint8Array(hex.length / 2);
    for (let i = 0; i < hex.length; i += 2) bytes[i / 2] = parseInt(hex.substr(i, 2), 16);
    return bytes;
  }
  bytesToBase58(bytes: Uint8Array | number[]) {
    const A = '123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
    let n = 0n;
    for (let i = 0; i < bytes.length; i++) n = n * 256n + BigInt(bytes[i]);
    let s = '';
    while (n > 0n) {
      s = A[Number(n % 58n)] + s;
      n /= 58n;
    }
    for (let i = 0; i < bytes.length && bytes[i] === 0; i++) s = '1' + s;
    return s;
  }

  async encryptClientBalance(balanceRaw: number, privateKeyB64: string) {
    const key = await this.deriveEncryptionKey(privateKeyB64);
    const pt = new TextEncoder().encode(balanceRaw.toString());
    const iv = crypto.getRandomValues(new Uint8Array(12));
    const k = await crypto.subtle.importKey('raw', key, { name: 'AES-GCM' }, false, ['encrypt']);
    const ct = await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, k, pt);
    const comb = new Uint8Array(iv.length + ct.byteLength);
    comb.set(iv);
    comb.set(new Uint8Array(ct), iv.length);
    return 'v2|' + this.bytesToBase64(comb);
  }

  async decryptClientBalance(encryptedData: string, privateKeyB64: string) {
    if (!encryptedData.startsWith('v2|')) return 0;
    const d = this.base64ToBytes(encryptedData.substring(3));
    const iv = d.slice(0, 12),
      ct = d.slice(12);
    const key = await this.deriveEncryptionKey(privateKeyB64);
    const k = await crypto.subtle.importKey('raw', key, { name: 'AES-GCM' }, false, ['decrypt']);
    try {
      const pt = await crypto.subtle.decrypt({ name: 'AES-GCM', iv }, k, ct);
      return parseInt(new TextDecoder().decode(pt));
    } catch (_e) {
      return 0;
    }
  }

  async deriveEncryptionKey(pkB64: string) {
    const pk = this.base64ToBytes(pkB64);
    const s = new TextEncoder().encode('octra_encrypted_balance_v2');
    const c = new Uint8Array(s.length + pk.length);
    c.set(s);
    c.set(pk, s.length);
    const h = await crypto.subtle.digest('SHA-256', c);
    return new Uint8Array(h).slice(0, 32);
  }

  deriveSharedSecretForClaim(privateKey: string, ephemeralPublicKey: string): Uint8Array | null {
    try {
      const privBytes = this.base64ToBytes(privateKey);
      const pubBytes = this.hexToBytes(ephemeralPublicKey);
      return nacl.box.before(pubBytes, privBytes.slice(0, 32));
    } catch {
      return null;
    }
  }

  async decryptPrivateAmount(encryptedAmount: string, sharedSecret: Uint8Array): Promise<number> {
    try {
      const data = this.base64ToBytes(encryptedAmount);
      const nonce = data.slice(0, 24);
      const ciphertext = data.slice(24);
      const decrypted = nacl.box.open.after(ciphertext, nonce, sharedSecret);
      if (!decrypted) return 0;
      return parseInt(new TextDecoder().decode(decrypted), 10);
    } catch {
      return 0;
    }
  }

  async encryptPrivateAmount(amount: number, sharedSecret: Uint8Array): Promise<string> {
    const message = new TextEncoder().encode(amount.toString());
    const nonce = nacl.randomBytes(24);
    const encrypted = nacl.box.after(message, nonce, sharedSecret);
    const combined = new Uint8Array(nonce.length + encrypted.length);
    combined.set(nonce);
    combined.set(encrypted, nonce.length);
    return this.bytesToBase64(combined);
  }

  signTransaction(message: string, privateKeyBase64: string) {
    try {
      const privateKeyBytes = this.base64ToBytes(privateKeyBase64);

      if (privateKeyBytes.length !== 32) {
        throw new Error('Invalid private key length. Expected 32 bytes.');
      }

      const keyPair = nacl.sign.keyPair.fromSeed(privateKeyBytes);
      const messageBytes = new TextEncoder().encode(message);
      const signature = nacl.sign.detached(messageBytes, keyPair.secretKey);

      // Return as base64 (not hex) to match legacy format
      return this.bytesToBase64(signature);
    } catch (error) {
      logger.error('Transaction signing error:', error);
      throw new Error(`Failed to sign transaction: ${error.message}`);
    }
  }
}

